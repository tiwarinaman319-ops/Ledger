function getLang() {
  return localStorage.getItem("ledger_lang") || "en";
}
function setLang(lang) {
  localStorage.setItem("ledger_lang", lang);
}
function t(key, vars) {
  const lang = getLang();
  let str = (I18N[lang] && I18N[lang][key]) || I18N.en[key] || key;
  if (vars) {
    Object.keys(vars).forEach((k) => {
      str = str.replace(`{${k}}`, vars[k]);
    });
  }
  return str;
}
function applyI18n() {
  const lang = getLang();
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    el.textContent = t(key);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    el.placeholder = t(key);
  });
  const langSelects = document.querySelectorAll("#languageSelect, .language-sync-select");
  langSelects.forEach((sel) => {
    if (sel) sel.value = lang;
  });
}
document.addEventListener("DOMContentLoaded", () => {
  applyI18n();
  const langSelects = document.querySelectorAll("#languageSelect, .language-sync-select");
  langSelects.forEach((sel) => {
    sel.addEventListener("change", (e) => {
      setLang(e.target.value);
      applyI18n();
      if (window.onLanguageChange) window.onLanguageChange();
    });
  });
});
